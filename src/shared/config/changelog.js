  function latest() {
    return ENTRIES[0];
  }

  function parts(version) {
    return String(version || '0').split('.').map(function (n) {
      var v = parseInt(n, 10);
      return isNaN(v) ? 0 : v;
    });
  }

  function compare(a, b) {
    var x = parts(a);
    var y = parts(b);
    for (var i = 0; i < 3; i++) {
      var d = (x[i] || 0) - (y[i] || 0);
      if (d) return d > 0 ? 1 : -1;
    }
    return 0;
  }

  function since(version) {
    if (!version) return ENTRIES.slice();
    return ENTRIES.filter(function (e) { return compare(e.version, version) > 0; });
  }

  function isNewerThan(version) {
    return compare(latest().version, version) > 0;
  }

